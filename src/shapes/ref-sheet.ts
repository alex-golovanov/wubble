const CMD = /([MLQCZ])|(-?\d*\.?\d+(?:e[-+]?\d+)?)/gi;

/** Map template path from viewBox into target bounds (uniform scale, centered). */
export function mapTemplatePath(
  path: string,
  viewBox: readonly [number, number, number, number],
  target: Bounds,
): string {
  const [vx, vy, vw, vh] = viewBox;
  const sx = target.width / vw;
  const sy = target.height / vh;
  const s = Math.min(sx, sy);
  const ox = target.x + (target.width - vw * s) / 2;
  const oy = target.y + (target.height - vh * s) / 2;
  const tx = (n: number) => roundN(ox + (n - vx) * s);
  const ty = (n: number) => roundN(oy + (n - vy) * s);

  const parts: string[] = [];
  let cmd = "";
  const nums: number[] = [];
  const flush = () => {
    if (!cmd) return;
    const c = cmd.toUpperCase();
    if (c === "Z") {
      parts.push("Z");
    } else if (c === "M" || c === "L") {
      for (let i = 0; i + 1 < nums.length; i += 2) {
        parts.push(`${i === 0 ? c : "L"} ${fmt(tx(nums[i]!))} ${fmt(ty(nums[i + 1]!))}`);
      }
    } else if (c === "Q") {
      for (let i = 0; i + 3 < nums.length; i += 4) {
        parts.push(
          `Q ${fmt(tx(nums[i]!))} ${fmt(ty(nums[i + 1]!))} ${fmt(tx(nums[i + 2]!))} ${fmt(ty(nums[i + 3]!))}`,
        );
      }
    } else if (c === "C") {
      for (let i = 0; i + 5 < nums.length; i += 6) {
        parts.push(
          `C ${fmt(tx(nums[i]!))} ${fmt(ty(nums[i + 1]!))} ${fmt(tx(nums[i + 2]!))} ${fmt(ty(nums[i + 3]!))} ${fmt(tx(nums[i + 4]!))} ${fmt(ty(nums[i + 5]!))}`,
        );
      }
    }
    nums.length = 0;
  };

  let m: RegExpExecArray | null;
  const re = new RegExp(CMD.source, "gi");
  while ((m = re.exec(path))) {
    if (m[1]) {
      flush();
      cmd = m[1];
    } else if (m[2] != null) {
      nums.push(Number(m[2]));
    }
  }
  flush();
  return parts.join(" ");
}


