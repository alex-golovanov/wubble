/** Map a content band onto a fitted frame as an absolute lettering box. */
export function contentBandBox(frame: Bounds, band: ContentBand): Bounds {
  const left = band.left ?? 0;
  const right = band.right ?? 1;
  const x = roundN(frame.x + frame.width * left);
  const y = roundN(frame.y + frame.height * band.top);
  const w = roundN(frame.width * Math.max(0.05, right - left));
  const h = roundN(frame.height * Math.max(0.05, band.bottom - band.top));
  return { x, y, width: Math.max(1, w), height: Math.max(1, h) };
}

function unionBounds(bodies: Bounds[]): Bounds {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const b of bodies) {
    minX = Math.min(minX, b.x);
    minY = Math.min(minY, b.y);
    maxX = Math.max(maxX, b.x + b.width);
    maxY = Math.max(maxY, b.y + b.height);
  }
  return {
    x: roundN(minX),
    y: roundN(minY),
    width: roundN(Math.max(1, maxX - minX)),
    height: roundN(Math.max(1, maxY - minY)),
  };
}

export function buildRefSheetShape(
  shapeId: RefShapeId,
  body: Bounds,
  lobeBodies: Bounds[] = [],
): ShapeGeometry {
  const tpl = REF_TEMPLATES[shapeId];
  const shape = PROFILE.shapes[shapeId];
  const frame = lobeBodies.length > 0 ? unionBounds([body, ...lobeBodies]) : body;
  // Tiny inset so stroke sits inside the placement frame
  const pad = Math.min(frame.width, frame.height) * 0.02;
  const target: Bounds = {
    x: frame.x + pad,
    y: frame.y + pad,
    width: Math.max(1, frame.width - pad * 2),
    height: Math.max(1, frame.height - pad * 2),
  };
  return {
    path: mapTemplatePath(tpl.path, tpl.viewBox, target),
    fill: shape.fill,
    stroke: shape.stroke,
    strokeWidth: shape.strokeWidth,
  };
}

